// normalised country NAME (and alias) → alpha-2 code.
const NAME_TO_CODE: Map<string, string> = (() => {
  const m = new Map<string, string>();
  for (const [code, name] of Object.entries(COUNTRY_NAME_BY_CODE)) {
    m.set(normalizeCountryName(name), code);
  }
  for (const [alias, code] of Object.entries(ALIASES)) {
    m.set(normalizeCountryName(alias), code);
  }
  return m;
})();

export interface ResolvedCountry {
  /** ISO alpha-2, or null if unrecognised (the row still shows its raw name). */
  code: string | null;
  /** Canonical display name, else the trimmed raw input. */
  name: string;
}

/** Resolve a VHP nationality (alpha-2 code OR a country name) to { code, name }. */
export function resolveCountry(input: string): ResolvedCountry {
  const raw = String(input ?? "").trim();
  if (!raw) return { code: null, name: "" };

  // An explicit alpha-2 code.
  const upper = raw.toUpperCase();
  if (/^[A-Z]{2}$/.test(upper) && COUNTRY_NAME_BY_CODE[upper]) {
    return { code: upper, name: COUNTRY_NAME_BY_CODE[upper]! };
  }

  const code = NAME_TO_CODE.get(normalizeCountryName(raw));
  if (code) return { code, name: COUNTRY_NAME_BY_CODE[code]! };

  return { code: null, name: raw };
}
